DROP TABLE IF EXISTS
    operacao,
    conta_bancaria,
    usuario,
    filial,
    resultado,
    receita,
    despesa,
    contabancaria
    CASCADE;

CREATE TABLE filial (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razao_social VARCHAR(255),
    nome_fantasia VARCHAR(255),
    cnpj VARCHAR(255),
    inscricao_estadual VARCHAR(255),
    inscricao_municipal VARCHAR(255),
    regime_tributario VARCHAR(255),
    cnae_principal VARCHAR(255),
    data_abertura VARCHAR(255),
    situacao_cadastral VARCHAR(255),
    endereco VARCHAR(500),
    token VARCHAR(255),
    cep VARCHAR(255),
    logradouro VARCHAR(255),
    numero VARCHAR(255),
    complemento VARCHAR(255),
    bairro VARCHAR(255),
    cidade VARCHAR(255),
    uf VARCHAR(255),
    pais VARCHAR(255),
    responsavel_nome VARCHAR(255),
    responsavel_cpf VARCHAR(255),
    responsavel_email VARCHAR(255),
    responsavel_telefone VARCHAR(255),
    responsavel_cargo VARCHAR(255),
    moeda_padrao VARCHAR(255),
    fuso_horario VARCHAR(255),
    plano_contas VARCHAR(255),
    data_inicio_operacao VARCHAR(255),
    centro_custo_padrao VARCHAR(255),
    exercicio_fiscal VARCHAR(255),
    empresas_vinculadas VARCHAR(255)
);

CREATE TABLE usuario (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255),
    cargo VARCHAR(255),
    email VARCHAR(255),
    senha VARCHAR(255),
    filial_id INTEGER,
    CONSTRAINT usuario_cargo_check
        CHECK (cargo IN ('ADMINISTRADOR', 'CONTADOR', 'FINANCEIRO', 'GERENTE')),
    CONSTRAINT fk_usuario_filial
        FOREIGN KEY (filial_id) REFERENCES filial(id)
);

CREATE TABLE conta_bancaria (
    id_conta_bancaria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_banco VARCHAR(255),
    nome_instituicao VARCHAR(255),
    agencia VARCHAR(255),
    agencia_digito VARCHAR(255),
    numero_conta VARCHAR(255),
    tipo_conta VARCHAR(255),
    cpf_cnpj_titular VARCHAR(255),
    nome_titular VARCHAR(255),
    ativo BOOLEAN,
    saldo NUMERIC(15, 2),
    filial_id INTEGER,
    CONSTRAINT fk_conta_bancaria_filial
        FOREIGN KEY (filial_id) REFERENCES filial(id)
);

CREATE TABLE operacao (
    id_operacao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    valor_operacao DOUBLE PRECISION,
    tipo_operacao SMALLINT,
    razao_social VARCHAR(255),
    categoria VARCHAR(255),
    dt_hora TIMESTAMP(6),
    fk_conta_bancaria BIGINT,
    CONSTRAINT operacao_tipo_operacao_check
        CHECK (tipo_operacao >= 0 AND tipo_operacao <= 1),
    CONSTRAINT fk_operacao_conta_bancaria
        FOREIGN KEY (fk_conta_bancaria) REFERENCES conta_bancaria(id_conta_bancaria)
);
